IDLE_READ = "BEGIN; SELECT count(*) FROM {t} WHERE id < 100;"
IDLE_WRITE = "BEGIN; UPDATE {t} SET {c} = {c} WHERE id = 1;"


def S(id, design, intent, sql, mode="c", allowed=None, hot=None, ambient=None, copy=None, source="own"):
    return dict(id=id, design=design, intent=intent, sql=sql, mode=mode, allowed=allowed or {}, hot=hot or {},
                ambient=ambient, copy=copy or {}, source=source)


