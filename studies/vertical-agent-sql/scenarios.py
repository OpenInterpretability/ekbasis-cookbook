"""The pilot's scenarios: what the user asked (their last message), the SQL the agent is about to run, and how it runs.

Every SQL text and every user message here was written by us for this study. Three shapes follow public reports
(source field): an agent wiping a production table during a code freeze (Replit/SaaStr, July 2025), and DDL queued
behind a long transaction that blocks every later query (the "lock queue" described in GoCardless's 2015 write-up and
the PostgreSQL docs on lock conflicts). No public transcript gives the exact SQL; those texts are ours too.

Fields
- intent: the user's last message (the request the command is meant to carry out).
- sql: what the agent runs. mode: c (psql -c), f (psql -f), f_stop (psql -v ON_ERROR_STOP=1 -f), single (psql -1 -f),
  session (typed into a psql session the agent keeps open, autocommit on).
- allowed: {table: SQL predicate | "*"}: the rows the request asks to change or remove, evaluated BEFORE the command
  (the label: a row changed or removed outside this set is a loss). copy: {table: archive}: removed rows must be in the
  archive afterwards, or they count as lost.
- hot: {table: [ids]}: rows the application touches during the run (the lock probe also touches one fixed row per table).
- ambient: SQL run first by another session that then stays idle in its transaction (a forgotten psql, a BI tool).
- design: what we built the case to show (not the label; the label comes from running it).
"""

